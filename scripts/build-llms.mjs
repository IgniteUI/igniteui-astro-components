#!/usr/bin/env node
/**
 * build-llms.mjs
 *
 * Generates `llms-full.txt`: a single file an AI agent (or a hosted indexer)
 * can read to learn the whole public surface of this package without opening
 * the sources. It concatenates, in a fixed order:
 *
 *   1. `llms.txt` (the hand-written index)
 *   2. a table of every `package.json#exports` subpath
 *   3. the root `README.md`
 *   4. every `src/∗∗/README.md`
 *
 * The output is deterministic (no version, date or git SHA) so that the
 * committed file can be diffed against a fresh build in `scripts/llms.test.mjs`.
 *
 *   node scripts/build-llms.mjs          # write llms-full.txt
 *   node scripts/build-llms.mjs --check  # exit 1 when the committed file is stale
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = `# igniteui-astro-components — full reference

> Everything an agent needs to use or change this package, in one file.
> Generated by \`scripts/build-llms.mjs\` from \`llms.txt\`, \`README.md\` and every
> \`src/**/README.md\`. Do not edit by hand: run \`npm run build:llms\`.
> The installed version is in \`package.json#version\` next to this file.
> Paths are relative to the package root (in a consumer:
> \`node_modules/igniteui-astro-components/\`).`;

/** Order READMEs so the file reads top-down: layout, chrome, sidebar, MDX. */
function readmeRank(rel) {
  if (rel.startsWith('src/layouts/')) return 0;
  if (rel.startsWith('src/components/mdx/')) return 2;
  if (rel.startsWith('src/components/')) return 1;
  return 3;
}

export function listReadmes(rootDir) {
  const srcDir = path.join(rootDir, 'src');
  const found = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name === 'README.md')
        found.push(path.relative(rootDir, full).split(path.sep).join('/'));
    }
  };
  walk(srcDir);
  // Byte-order sort inside each rank keeps the output identical on every OS.
  return found.sort((a, b) => readmeRank(a) - readmeRank(b) || (a < b ? -1 : a > b ? 1 : 0));
}

function exportKind(target) {
  if (target.endsWith('.astro')) return target.includes('/layouts/') ? 'layout' : 'component';
  if (target.includes('/plugins/')) return 'plugin';
  if (target.endsWith('.scss') || target.endsWith('.css')) return 'styles';
  return 'module';
}

export function exportsTable(pkg) {
  const rows = Object.entries(pkg.exports ?? {})
    .filter(([key]) => key !== './package.json')
    .map(([key, value]) => {
      const target = typeof value === 'string' ? value : (value.default ?? value.import ?? '');
      const subpath = key === '.' ? pkg.name : `${pkg.name}/${key.slice(2)}`;
      return `| \`${subpath}\` | \`${target.replace(/^\.\//, '')}\` | ${exportKind(target)} |`;
    });
  return ['| Subpath | Source | Kind |', '| --- | --- | --- |', ...rows].join('\n');
}

/** Demote ATX headings by one level, leaving fenced code blocks untouched. */
function demote(markdown) {
  let inFence = false;
  let fenceMarker = '';
  return markdown
    .split('\n')
    .map((line) => {
      const fence = line.match(/^\s*(`{3,}|~{3,})/);
      if (fence) {
        if (!inFence) {
          inFence = true;
          fenceMarker = fence[1][0];
        } else if (fence[1][0] === fenceMarker) {
          inFence = false;
        }
        return line;
      }
      if (inFence) return line;
      const heading = line.match(/^(#{1,5})(\s+.*)$/);
      return heading ? `#${heading[1]}${heading[2]}` : line;
    })
    .join('\n');
}

/** Rewrite relative Markdown link targets so they resolve from the package root. */
function rebaseLinks(markdown, fromDir) {
  return markdown.replace(/\]\(([^)\s]+)(\s+"[^"]*")?\)/g, (match, target, title = '') => {
    if (/^(https?:|mailto:|#|\/)/.test(target)) return match;
    const [file, hash] = target.split('#');
    const rebased = path.posix.normalize(path.posix.join(fromDir, file));
    return `](${rebased}${hash ? `#${hash}` : ''}${title})`;
  });
}

function normalize(text) {
  return text
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => line.replace(/\s+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

export function buildLlmsFull(rootDir) {
  const read = (rel) => fs.readFileSync(path.join(rootDir, rel), 'utf8');
  const pkg = JSON.parse(read('package.json'));

  const sections = [
    HEADER,
    `## llms.txt\n\n${demote(read('llms.txt'))}`,
    `## Subpath exports\n\n${exportsTable(pkg)}`,
    `## README.md\n\n${demote(rebaseLinks(read('README.md'), '.'))}`,
    ...listReadmes(rootDir).map(
      (rel) => `## ${rel}\n\n${demote(rebaseLinks(read(rel), path.posix.dirname(rel)))}`,
    ),
  ];

  return `${sections.map(normalize).join('\n\n\n')}\n`;
}

const isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isCli) {
  const rootDir = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
  const outFile = path.join(rootDir, 'llms-full.txt');
  const fresh = buildLlmsFull(rootDir);

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current !== fresh) {
      console.error(
        'llms-full.txt is out of date. Run `npm run build:llms` and commit the result.',
      );
      process.exit(1);
    }
    console.log('llms-full.txt is up to date.');
  } else {
    fs.writeFileSync(outFile, fresh);
    console.log(
      `Wrote ${path.relative(process.cwd(), outFile)} (${fresh.length.toLocaleString()} chars).`,
    );
  }
}
